const cleanupFns: (() => void)[] = [];

function trackCleanup(server: http.Server, ...sockets: net.Socket[]) {
  cleanupFns.push(() => {
    for (const s of sockets) {
      if (!s.destroyed) s.destroy();
    }
    server.closeAllConnections();
    server.close();
  });
}

afterEach(() => {
  for (const fn of cleanupFns) fn();
  cleanupFns.length = 0;
});

